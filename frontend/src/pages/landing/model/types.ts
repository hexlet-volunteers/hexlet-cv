import { type Icon } from '@tabler/icons-react'

/**
 * Описывает структуру карточки функционала (преимущества) платформы.
 * Используется для рендеринга промо-блоков и списков фич.
 */
export interface Feature {
  /** Уникальный идентификатор фичи для React-ключей и навигации. */
  id: string

  /** Короткий заголовок фичи, раскрывающий её суть. */
  title: string

  /** Подробное текстовое описание возможностей и пользы для пользователя. */
  text: string

  /**
   * Текст шильдика (badge) над заголовком карточки.
   * Используется для выделения уникальности фичи.
   */
  badge?: string

  /** Компонент иконки из библиотеки `@tabler/icons-react`. */
  icon: Icon

  /**
   * Флаг инверсии цвета.
   * Если `true`, карточка рендерится в тёмной теме для визуального акцента.
   */
  isDark?: boolean
}
