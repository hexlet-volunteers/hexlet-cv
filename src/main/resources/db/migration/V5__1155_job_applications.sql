CREATE TABLE job_applications (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id           bigint       NOT NULL,
    resume_id         bigint,
    company           varchar(255) NOT NULL,
    position          varchar(255) NOT NULL,
    salary            varchar(255),
    vacancy_url       varchar(1000),
    source            varchar(255),
    stage             varchar(32)  NOT NULL,
    rejected_at_stage varchar(32),
    deadline          date,
    next_step_title   varchar(255),
    next_step_at      timestamp(6),
    last_event_at     timestamp(6) NOT NULL,
    created_at        timestamp(6),
    updated_at        timestamp(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_job_applications_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_job_applications_resume FOREIGN KEY (resume_id) REFERENCES resumes (id) ON DELETE SET NULL
);

CREATE INDEX idx_job_applications_user_id ON job_applications (user_id);

CREATE TABLE job_application_events (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    application_id bigint       NOT NULL,
    type           varchar(32)  NOT NULL,
    text           varchar(1000) NOT NULL,
    occurred_at    timestamp(6) NOT NULL,
    created_at     timestamp(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_job_application_events_application
        FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE
);

CREATE INDEX idx_job_application_events_application_id ON job_application_events (application_id);
